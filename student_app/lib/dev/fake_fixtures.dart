  'id': id,
  'exam_key': key,
  'exam_year': year,
  'session': session,
  'class_level': classLevel,
  'stream': stream,
  'subject': subject,
  'language': language,
  'duration_minutes': duration,
  'is_free': free,
  'unlock_cost': free ? 0 : cost,
  'practice_enabled': true,
  'status': 'published',
  'published_at': publishedAt,
};

Map<String, Object?> _stimulus({
  required String id,
  required String text,
  String kind = 'passage',
  String? title,
}) => <String, Object?>{
  'id': id,
  'kind': kind,
  'title': title,
  'text': text,
  'sort_order': 0,
};

Map<String, Object?> _q({
  required String id,
  required String path,
  required String type,
  required String text,
  String? parentId,
  String? stimulusId,
  List<String> options = const <String>[],
  double marks = 1,
  int sortOrder = 0,
  String access = 'paid',
  String markingMethod = 'auto',
  Object? key,
  List<String> alternatives = const <String>[],
  String? explanation,
  String? modelAnswer,
  bool container = false,
  int children = 0,
  int difficulty = 3,
}) => <String, Object?>{
  'id': id,
  'parent_id': parentId,
  'path': path,
  'type': type,
  'stimulus_id': stimulusId,
  'text': text,
  'options': options,
  'marks': container ? 0 : marks,
  'sort_order': sortOrder,
  'difficulty': difficulty,
  'access': access,
  'practice_eligible': !container,
  'key_status': container ? 'approved' : (key == null ? 'pending' : 'approved'),
  'marking_method': container ? null : markingMethod,
  'is_container': container,
  'children_count': children,
  'key': key,
  'accepted_alternatives': alternatives,
  'explanation': explanation,
  'model_answer': modelAnswer,
};

